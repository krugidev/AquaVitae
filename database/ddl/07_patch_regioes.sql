-- AquaVitae — Patch incremental (2026-09-19)
-- Regiões como lookup (decisão do utilizador, "opção B"): tabela `regiao` (país + nome) e `produtor` passa a
-- apontar para ela (`produtor_regiao_id`) em vez do texto livre `produtor_regiao`.
--   1. Schema: `regiao` e `produtor.produtor_regiao_id`.
--   2. Regiões dos países mais populares (as mesmas de seed/01_lookups.sql).
--   3. Migra os produtores existentes do texto para a região e apaga a coluna de texto. Os valores compostos
--      ("Vinho Verde — Melgaço") passam à região (a localidade perde-se); os sem correspondência (Peniche,
--      Lousã — Beira Litoral) ficam NULL = "não disponível" e são listados antes de a coluna ser apagada.
--   4. FK composta (a região de um produtor tem de ser do país desse produtor) + CHECK.
--
-- Só correr numa BD de DEV criada antes deste patch (quem reconstruir a BD do zero já tem tudo em 01_tables.sql /
-- 02_constraints.sql / seed). Tal como 04 a 06, NÃO faz parte do run-migrations. É repetível: cada passo ignora o
-- que já existe. Se falhar, reverte o DML (o DDL já executado fica; volta a correr sem problema).
--
-- Uso manual (com NLS_LANG, ver database/README.md). Envia sempre o ficheiro, nunca SQL inline:
--   docker cp ddl/07_patch_regioes.sql aquavitae-oracle-xe:/tmp/07.sql
--   docker exec -e NLS_LANG=AMERICAN_AMERICA.AL32UTF8 aquavitae-oracle-xe sqlplus -s "<user>/<pass>@//localhost:1521/XEPDB1" @/tmp/07.sql
