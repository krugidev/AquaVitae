-- ============================================================
-- BEBIDA (supertype)
-- ============================================================

CREATE TABLE bebida (
    bebida_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bebida_category_id       NUMBER,
    bebida_name               VARCHAR2(150 CHAR),
    bebida_producer_id        NUMBER,
    bebida_pais_origem_id     NUMBER,
    bebida_ano_producao       NUMBER(4),
    bebida_teor_alcoolico     NUMBER(4,2),
    bebida_volume_ml          NUMBER,
    -- Caminho relativo (recurso estático do backend) OU URL absoluto (imagem do retalhista/feed): 1000 porque os URLs
    -- de imagem dos retalhistas levam parâmetros e passam facilmente dos 255.
    bebida_path_image         VARCHAR2(1000 CHAR),
    bebida_data_criacao       TIMESTAMP DEFAULT SYSTIMESTAMP,
    bebida_rating_medio       NUMBER(3,2) DEFAULT 0,
    bebida_total_reviews      NUMBER DEFAULT 0,
    -- GTIN da bebida (EAN-8, UPC-A/12, EAN-13 ou GTIN-14), em TEXTO (zeros à esquerda). Único: é como se reconhece a
    -- mesma bebida vinda de outro retalhista (só se junta um link novo). Anulável: nem todo o feed/página o traz
    -- (vários NULL são permitidos pelo UNIQUE). Não é exposto na API.
    bebida_ean                VARCHAR2(14 CHAR) CONSTRAINT ck_bebida_ean CHECK (REGEXP_LIKE(bebida_ean, '^[0-9]{8,14}$')),
    CONSTRAINT uq_bebida_ean UNIQUE (bebida_ean)
);

