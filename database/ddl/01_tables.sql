-- ============================================================
-- PRODUTOR / RETALHISTA
-- ============================================================

-- Região de um país (Douro, Rioja, Bordéus, ...): é o que o filtro "Origem" do catálogo mostra depois do país.
-- O 2.º UNIQUE (país, id) existe só para a FK composta de `produtor` (ver 02_constraints.sql): a região de um
-- produtor tem de ser do país desse produtor. O país é `produtor_pais` (mesmos ids que `pais`, ver database/README.md).
CREATE TABLE regiao (
    regiao_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regiao_nome     VARCHAR2(100 CHAR),
    regiao_pais_id  NUMBER,
    CONSTRAINT uq_regiao_pais_nome UNIQUE (regiao_pais_id, regiao_nome),
    CONSTRAINT uq_regiao_pais_id UNIQUE (regiao_pais_id, regiao_id)
);

CREATE TABLE produtor (
    produtor_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produtor_nome             VARCHAR2(150 CHAR),
    produtor_pais_id          NUMBER,
    produtor_regiao_id        NUMBER,
    produtor_historia         CLOB,
    produtor_ano_fundacao     NUMBER(4),
    produtor_website          VARCHAR2(255 CHAR),
    produtor_path_imagem      VARCHAR2(255 CHAR),
    -- Morada em texto livre (rua, código postal, localidade), para a página do produtor; NULL = não disponível.
    produtor_morada           VARCHAR2(300 CHAR),
    produtor_latitude         NUMBER(9,6),
    produtor_longitude        NUMBER(9,6),
    produtor_permite_visitas  NUMBER(1) DEFAULT 0 CHECK (produtor_permite_visitas IN (0, 1)),
    produtor_data_criacao     TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE retalhista (
