    retalhista_rede_afiliados         VARCHAR2(50 CHAR),
    retalhista_codigo_afiliado        VARCHAR2(100 CHAR),
    retalhista_comissao_percentagem   NUMBER(5,2),
    retalhista_is_ativo               NUMBER(1) DEFAULT 1 CHECK (retalhista_is_ativo IN (0, 1)),
    retalhista_data_criacao           TIMESTAMP DEFAULT SYSTIMESTAMP
