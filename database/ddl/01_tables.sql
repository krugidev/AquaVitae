--------------------------------------------------------------------------------
-- AquaVitae — DDL Oracle (tabelas)
-- Gerado a partir do schema DBML do briefing do MVP.
-- Convenções: PKs com IDENTITY (exceto tabelas subtype, cujo bebida_id
-- é herdado de `bebida`), VARCHAR2(n CHAR) para suportar acentuação PT,
-- CLOB para texto livre, NUMBER(1) + CHECK para booleanos (sem tipo
-- BOOLEAN nativo em Oracle XE 18c/21c).
--
-- Nota de correção: `vinho_tipo.vinho_tipo_value` estava definido como
-- `integer` no DBML original — claramente inconsistente com as restantes
-- tabelas de lookup do mesmo padrão (vinho_corpo, vinho_tanino, etc., todas
-- VARCHAR2). Corrigido aqui para VARCHAR2(30 CHAR); sinalizado ao utilizador.
--
-- As foreign keys ficam em 02_constraints.sql (evita depender da ordem
-- de criação das tabelas).
--------------------------------------------------------------------------------

